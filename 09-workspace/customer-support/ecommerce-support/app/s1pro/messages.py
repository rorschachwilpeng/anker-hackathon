"""S1 Pro 演示的面向用户话术。

所有用户可见文案集中在本模块，按场景分组；流程逻辑见 flow.py。
语气约定：自称"我"，双方"咱们"；先承接、后行动；
能力边界与"本地演示"标注必须保留——只改说法，不改事实。

变体池约定：主要场景提供 2 条以上等价变体，经 pick() 确定性轮换，
消灭"复读机感"；同一变体池内的所有文案必须保留相同的事实、
边界标注与关键子串（按钮名「可以建单」、"不会再犯"等锚点）。
"""


def pick(pool, seed):
    """确定性轮换：同一会话同一场景说法稳定，跨会话/跨轮次呈现不同说法。"""
    return pool[seed % len(pool)]


